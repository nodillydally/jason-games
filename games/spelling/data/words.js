/* words.js — the Spelling word list.
 *
 * The game SAYS the word — that is the prompt. Everything here is what a bee
 * lets you ask the judge for on top of it: what it means, a sentence with the
 * word cut out, which trap it belongs to, and how hard it is.
 *
 * `def` and `sent` are held back until asked, with one exception: sound alone
 * cannot ask for a homophone, so the `homophones` category always shows its
 * sentence. Write those sentences so they actually disambiguate — "the new
 * rule had no ___ on the queue" only works if it cannot take `affect`.
 *
 * `cat` is the TRAP, not the topic — words are grouped by the mistake they
 * invite (a doubled letter, a silent letter, an -ible that wants to be -able),
 * because that's the thing being learned. Spelling one word right is worth
 * little; recognising that "-ence follows a soft c" is worth the whole
 * category. Each category carries its own Elo, so the stats screen says which
 * trap you're still falling into rather than which words you missed.
 *
 * `tier` 1-5 is the difficulty the adaptive engine serves against — tier 1 is
 * a word most adults spell right, tier 5 is one most adults don't.
 *
 * `sent` always contains "___" where the word goes. Never write the word into
 * the sentence: the clue is the whole question.
 *
 * `near` is an optional real confusable — its homophone or look-alike. The
 * multiple-choice builder prefers it over a generated misspelling, because
 * "principal vs principle" is a better wrong answer than "principel".
 */

