/**
 * generate-map-data.mjs
 *
 * Generates the game's country data file (data/countries.js) from the
 * Natural Earth 1:110m dataset (public domain, via the world-atlas npm
 * package). Country names / continents come from the world-countries
 * package, joined on ISO 3166-1 numeric codes.
 *
 * Usage:
 *   npm install world-atlas@2 topojson-client@3 d3-geo@3 world-countries@5
 *   node generate-map-data.mjs <output-path>
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import * as topojson from 'topojson-client';
import { geoNaturalEarth1, geoPath } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/countries-110m.json');
const worldCountries = require('world-countries');

const WIDTH = 1000;
const HEIGHT = 520;

const outPath = process.argv[2] || 'countries.js';

// Join key: ISO 3166-1 numeric, zero-padded to 3 chars.
const metaByCcn3 = new Map(worldCountries.map((c) => [c.ccn3, c]));

const geo = topojson.feature(topo, topo.objects.countries);

// Drop Antarctica and anything we can't identify before fitting the
// projection, so the map uses the full canvas for quizzable countries.
const features = geo.features.filter((f) => {
  const meta = metaByCcn3.get(String(f.id).padStart(3, '0'));
  return meta && meta.region && meta.region !== 'Antarctic';
});

const projection = geoNaturalEarth1().fitExtent(
  [[4, 4], [WIDTH - 4, HEIGHT - 4]],
  { type: 'FeatureCollection', features }
);
const pathGen = geoPath(projection);

function continentOf(meta) {
  if (meta.region === 'Americas') {
    return meta.subregion === 'South America' ? 'South America' : 'North America';
  }
  return meta.region; // Africa, Asia, Europe, Oceania
}

// Bounding box of the country's largest polygon (projected). Using the
// largest polygon keeps zoom sane for countries with far-flung territory
// (France + French Guiana, USA + Hawaii, etc.).
function mainlandBounds(feature) {
  if (feature.geometry.type === 'Polygon') return pathGen.bounds(feature);
  let best = null;
  let bestArea = -1;
  for (const coords of feature.geometry.coordinates) {
    const poly = { type: 'Feature', geometry: { type: 'Polygon', coordinates: coords } };
    const area = pathGen.area(poly);
    if (area > bestArea) {
      bestArea = area;
      best = poly;
    }
  }
  return pathGen.bounds(best);
}

const round = (s) => s.replace(/\d+\.\d+/g, (m) => (+m).toFixed(1));
const r1 = (n) => Math.round(n * 10) / 10;

const countries = [];
for (const f of features) {
  const ccn3 = String(f.id).padStart(3, '0');
  const meta = metaByCcn3.get(ccn3);
  const d = pathGen(f);
  if (!d) continue;
  const [[x0, y0], [x1, y1]] = mainlandBounds(f);
  const alt = [...new Set([meta.name.official, ...(meta.altSpellings || [])])].filter(
    (a) => a && a.toLowerCase() !== meta.name.common.toLowerCase()
  );
  countries.push({
    id: ccn3,
    cca2: meta.cca2,
    name: meta.name.common,
    continent: continentOf(meta),
    capital: (meta.capital && meta.capital[0]) || null,
    flag: meta.flag || null,
    alt,
    box: [r1(x0), r1(y0), r1(x1), r1(y1)],
    d: round(d),
  });
}

countries.sort((a, b) => a.name.localeCompare(b.name));

const byContinent = {};
for (const c of countries) byContinent[c.continent] = (byContinent[c.continent] || 0) + 1;
console.log(`${countries.length} countries:`, byContinent);

const body = countries
  .map((c) => JSON.stringify(c))
  .join(',\n');

const out = `// Generated by tools/generate-map-data.mjs — do not edit by hand.
// Geometry: Natural Earth 1:110m via world-atlas (public domain).
// Names/continents: world-countries (ODbL-free, MIT-style "world-countries" data).
const MAP_WIDTH = ${WIDTH};
const MAP_HEIGHT = ${HEIGHT};
const COUNTRIES = [
${body}
];
`;

fs.mkdirSync(path.dirname(path.resolve(outPath)), { recursive: true });
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${(out.length / 1024).toFixed(0)} KB)`);
